I18N.de = I18N.en;
I18N.fr = I18N.en;
I18N.it = I18N.en;
I18N.es = I18N.en;
I18N.pl = I18N.en;

(function () {
  const HERO = {
    nl: 'assets/hero-nl.png',
    en: 'assets/hero-en.png',
  };
  function apply(lang) {
    const dict = I18N[lang] || I18N.en;
    for (const el of document.querySelectorAll('[data-i18n]')) {
      const k = el.getAttribute('data-i18n');
      if (dict[k] != null) el.innerHTML = dict[k];
    }
    document.documentElement.lang = lang;
    const heroImg = document.getElementById('hero-img');
    if (heroImg) heroImg.src = HERO[lang] || HERO.en;
    const t = document.querySelector('title');
    if (t && dict.page_title) t.textContent = dict.page_title;
    const md = document.querySelector('meta[name="description"]');
    if (md && dict.sub) md.setAttribute('content', dict.sub.replace(/<[^>]+>/g, ''));
    try { localStorage.setItem('jm-rec-lang', lang); } catch (e) {}
    for (const btn of document.querySelectorAll('nav.lang button')) {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    }
  }
  function detect() {
    try {
      const saved = localStorage.getItem('jm-rec-lang');
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    const nav = (navigator.language || 'en').toLowerCase().slice(0, 2);
    return I18N[nav] ? nav : 'en';
  }
  for (const btn of document.querySelectorAll('nav.lang button')) {
    btn.addEventListener('click', () => apply(btn.dataset.lang));
  }
  apply(detect());
})();
